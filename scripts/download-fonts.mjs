/**
 * Downloads self-hosted web fonts (SIL Open Font License) from Google Fonts
 * and generates src/styles/fonts.css with local @font-face rules.
 *
 * Run once:  node scripts/download-fonts.mjs
 * Only latin / latin-ext / arabic subsets are kept to keep the site fast.
 */
import { mkdir, writeFile, readdir, unlink } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const FONT_DIR = path.join(ROOT, "public", "fonts");
const CSS_OUT = path.join(ROOT, "src", "styles", "fonts.css");

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36";

const FAMILIES = [
  { css: "Source+Serif+4:ital,wght@0,400;0,600;0,700;1,400", slug: "source-serif-4" },
  { css: "Source+Sans+3:wght@400;500;600;700", slug: "source-sans-3" },
  { css: "Amiri:wght@400;700", slug: "amiri" },
  { css: "Amiri+Quran", slug: "amiri-quran" },
];

const KEEP_RANGES = ["U+0000-00FF", "U+0100-02BA", "U+0600-06FF"];

async function main() {
  if (existsSync(FONT_DIR)) {
    for (const f of await readdir(FONT_DIR)) {
      if (f.endsWith(".woff2")) await unlink(path.join(FONT_DIR, f));
    }
  }
  await mkdir(FONT_DIR, { recursive: true });
  await mkdir(path.dirname(CSS_OUT), { recursive: true });

  const url =
    "https://fonts.googleapis.com/css2?" +
    FAMILIES.map((f) => `family=${f.css}`).join("&") +
    "&display=swap";

  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`Google Fonts CSS request failed: ${res.status}`);
  const css = await res.text();

  const blocks = css.match(/@font-face\s*\{[^}]+\}/g) ?? [];
  const faces = [];
  let kept = 0;
  let skipped = 0;

  for (const block of blocks) {
    const family = /font-family:\s*'([^']+)'/.exec(block)?.[1];
    const style = /font-style:\s*(\w+)/.exec(block)?.[1] ?? "normal";
    const weight = /font-weight:\s*(\d+)/.exec(block)?.[1] ?? "400";
    const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1]?.trim() ?? "";
    const src = /url\((https:\/\/[^)]+)\)/.exec(block)?.[1];
    if (!family || !src) continue;

    if (!KEEP_RANGES.some((r) => range.includes(r))) {
      skipped++;
      continue;
    }

    const slug =
      FAMILIES.find((f) => family.replace(/\s+/g, "+") === f.css.split(":")[0])?.slug ??
      family.toLowerCase().replace(/\s+/g, "-");

    const name = `${slug}-${weight}-${style}-${kept}.woff2`;
    const fileRes = await fetch(src, { headers: { "User-Agent": UA } });
    if (!fileRes.ok) throw new Error(`Font download failed: ${src}`);
    await writeFile(path.join(FONT_DIR, name), Buffer.from(await fileRes.arrayBuffer()));
    kept++;

    faces.push(
      [
        "@font-face {",
        `  font-family: '${family}';`,
        `  font-style: ${style};`,
        `  font-weight: ${weight};`,
        "  font-display: swap;",
        `  src: url('/fonts/${name}') format('woff2');`,
        range ? `  unicode-range: ${range};` : "",
        "}",
      ]
        .filter(Boolean)
        .join("\n"),
    );
  }

  const header = [
    "/*",
    " * Self-hosted web fonts (generated by scripts/download-fonts.mjs).",
    " * Source Serif 4, Source Sans 3, Amiri, Amiri Quran - SIL Open Font License 1.1.",
    " */",
    "",
  ].join("\n");

  await writeFile(CSS_OUT, `${header}${faces.join("\n\n")}\n`, "utf8");
  console.log(`fonts.css written with ${kept} faces (${skipped} non-latin/arabic subsets skipped).`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
